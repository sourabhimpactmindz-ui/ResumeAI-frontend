import { useState } from "react";
import ScoreRing from "./ScoreRing";
import ProgressBar from "./ProgressBar";
import { Card } from "./Card";
import { Badge } from "./Badge";
import { Button } from "./Button";
import StaggerFromEdges from "./animations/StaggerFromEdges";
import {
  CheckCircle2,
  AlertTriangle,
  Sparkles,
  Download,
  Copy,
  Check,
  Target,
  FileText,
  ShieldCheck,
  Zap,
} from "lucide-react";
import { toast } from "react-toastify";

export default function AnalysisPanel({
  atsScore = 78,
  matchingSkills = [],
  missingSkills = [],
  strengths = [],
  aiSuggestions = [],
  onReset,
}) {
  const [copiedIndex, setCopiedIndex] = useState(null);

  const handleCopy = (text, idx) => {
    navigator.clipboard.writeText(text);
    setCopiedIndex(idx);
    toast.success("Bullet point copied to clipboard!");
    setTimeout(() => setCopiedIndex(null), 2000);
  };

  const handleDownloadReport = () => {
    const report = `
========================================
RESUMEAI — ATS DIAGNOSTIC REPORT
========================================
Overall ATS Match Score: ${atsScore}/100

MATCHING SKILLS DETECTED:
${matchingSkills.map((s) => `• ${s}`).join("\n") || "None specified"}

MISSING SKILLS & KEYWORD GAPS:
${missingSkills.map((s) => `• ${s}`).join("\n") || "None specified"}

KEY STRENGTHS:
${strengths.map((s) => `• ${s}`).join("\n") || "None specified"}

ACTIONABLE AI BULLET SUGGESTIONS:
${aiSuggestions.map((s, i) => `${i + 1}. ${s}`).join("\n\n") || "None specified"}

Generated by ResumeAI (https://resumeai.app)
100% Private in-memory diagnostic
========================================
    `;

    const blob = new Blob([report], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `ResumeAI-Diagnostic-Score-${atsScore}.txt`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success("Diagnostic report downloaded!");
  };

  return (
    <div className="w-full max-w-5xl mx-auto space-y-10 animate-in fade-in duration-500">
      {/* Top Header Card with Score & Actions */}
      <Card
        className="p-8 md:p-12 rounded-[36px] bg-gradient-to-br from-c-800 to-c-800/60 border border-c-700/80 shadow-[0_28px_60px_-15px_rgba(6,20,27,0.9),0_0_40px_rgba(155,168,171,0.15)] flex flex-col md:flex-row items-center justify-between gap-8 text-center md:text-left"
        glow={true}
      >
        <div className="flex flex-col md:flex-row items-center gap-8">
          <ScoreRing
            score={atsScore}
            maxScore={100}
            size={170}
            strokeWidth={13}
            label=""
          />

          <div className="space-y-2">
            <div className="flex items-center justify-center md:justify-start gap-2">
              <Badge
                variant={atsScore >= 80 ? "success" : atsScore >= 60 ? "warning" : "error"}
                pulsing={true}
              >
                {atsScore >= 80 ? "Top 10% Candidate Pool" : atsScore >= 60 ? "Baseline Passed" : "Needs Keyword Revision"}
              </Badge>
              <span className="text-xs text-c-600 font-sans">· Scanned with AI</span>
            </div>

            <h2 className="font-heading font-extrabold text-2xl md:text-3xl text-c-100">
              {atsScore >= 80
                ? "Excellent ATS Alignment"
                : atsScore >= 60
                ? "Solid Foundation with Keyword Gaps"
                : "High Risk of Automated Filter Rejection"}
            </h2>

            <p className="text-sm text-c-300 font-sans max-w-md leading-relaxed">
              {atsScore >= 80
                ? "Your resume strongly matches the language, hard skills, and experience markers expected by ATS algorithms."
                : "Recruiters searching for exact skills from this job post will rank you higher once missing terminology is added."}
            </p>
          </div>
        </div>

        <div className="flex flex-col sm:flex-row md:flex-col gap-3 shrink-0 w-full sm:w-auto">
          <Button
            onClick={handleDownloadReport}
            variant="primary"
            size="md"
            icon={<Download size={16} />}
          >
            Download Report
          </Button>
          {onReset && (
            <Button
              onClick={onReset}
              variant="secondary"
              size="md"
              icon={<Zap size={16} />}
            >
              Scan Another Resume
            </Button>
          )}
        </div>
      </Card>

      {/* Category Progress Bars Grid */}
      <StaggerFromEdges
        itemSelector=".cat-card"
        className="grid grid-cols-1 md:grid-cols-2 gap-6"
      >
        <Card className="cat-card p-6 md:p-8" glow={false}>
          <ProgressBar
            label="Keyword Match & Density"
            hint="Core job requirements"
            value={Math.min(atsScore + 2, 98)}
            delay={0.1}
          />
          <p className="mt-3 text-xs text-c-600 font-sans">
            Compares explicit skill tokens against target job description requirements.
          </p>
        </Card>

        <Card className="cat-card p-6 md:p-8" glow={false}>
          <ProgressBar
            label="Format & Parsing Traps"
            hint="Columns, tables, headers"
            value={Math.max(atsScore - 5, 84)}
            delay={0.2}
          />
          <p className="mt-3 text-xs text-c-600 font-sans">
            Ensures text flow is linear with standard UTF-8 parsing compliance.
          </p>
        </Card>

        <Card className="cat-card p-6 md:p-8" glow={false}>
          <ProgressBar
            label="Section Architecture & Hierarchy"
            hint="Experience, Education, Skills"
            value={94}
            delay={0.3}
          />
          <p className="mt-3 text-xs text-c-600 font-sans">
            Validates standard heading labels recognized by Workday and Greenhouse.
          </p>
        </Card>

        <Card className="cat-card p-6 md:p-8" glow={false}>
          <ProgressBar
            label="Measurable Impact & Metrics"
            hint="Action verbs & business metrics"
            value={Math.min(atsScore + 4, 90)}
            delay={0.4}
          />
          <p className="mt-3 text-xs text-c-600 font-sans">
            Measures presence of quantifiable achievements (% lift, revenue, latency, users).
          </p>
        </Card>
      </StaggerFromEdges>

      {/* Skills Matrix: Found vs Missing */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-8">
        {/* MATCHING SKILLS */}
        <Card className="p-8" glow={true}>
          <div className="flex items-center gap-3 mb-6">
            <div className="w-10 h-10 rounded-xl bg-c-success/20 text-c-success border border-c-success/40 flex items-center justify-center">
              <CheckCircle2 size={20} />
            </div>
            <div>
              <h3 className="font-heading font-bold text-lg text-c-100">
                Matching Skills Found ({matchingSkills.length})
              </h3>
              <p className="text-xs text-c-600 font-sans">
                These keywords are matched and indexed properly.
              </p>
            </div>
          </div>

          <div className="flex flex-wrap gap-2">
            {matchingSkills.length > 0 ? (
              matchingSkills.map((skill, idx) => (
                <span
                  key={idx}
                  className="px-3 py-1 rounded-full bg-c-success/15 border border-c-success/30 text-c-success text-xs font-heading font-semibold flex items-center gap-1.5"
                >
                  <Check size={12} />
                  <span>{skill}</span>
                </span>
              ))
            ) : (
              <span className="text-xs text-c-600 font-sans italic">
                No overlapping keywords detected in document.
              </span>
            )}
          </div>
        </Card>

        {/* MISSING SKILLS / KEYWORD GAPS */}
        <Card className="p-8" glow={true}>
          <div className="flex items-center gap-3 mb-6">
            <div className="w-10 h-10 rounded-xl bg-c-warning/20 text-c-warning border border-c-warning/40 flex items-center justify-center">
              <Target size={20} />
            </div>
            <div>
              <h3 className="font-heading font-bold text-lg text-c-100">
                Keyword Gaps ({missingSkills.length})
              </h3>
              <p className="text-xs text-c-600 font-sans">
                High-priority terms in the job description absent from your resume.
              </p>
            </div>
          </div>

          <div className="flex flex-wrap gap-2">
            {missingSkills.length > 0 ? (
              missingSkills.map((skill, idx) => (
                <span
                  key={idx}
                  className="px-3 py-1 rounded-full bg-c-warning/15 border border-c-warning/30 text-c-warning text-xs font-heading font-semibold flex items-center gap-1.5"
                >
                  <AlertTriangle size={12} />
                  <span>{skill}</span>
                </span>
              ))
            ) : (
              <span className="text-xs text-c-success font-sans">
                Zero keyword gaps! Full alignment detected.
              </span>
            )}
          </div>
        </Card>
      </div>

      {/* AI Bullet Suggestions with One-Click Copy */}
      {aiSuggestions.length > 0 && (
        <Card className="p-8 md:p-10" glow={true}>
          <div className="flex items-center gap-3 mb-6">
            <div className="w-10 h-10 rounded-xl bg-c-700/80 border border-c-600/70 flex items-center justify-center text-c-100">
              <Sparkles size={20} />
            </div>
            <div>
              <h3 className="font-heading font-bold text-xl text-c-100">
                Recommended Bullet Enhancements
              </h3>
              <p className="text-xs text-c-600 font-sans">
                Pre-formatted with action verbs, keywords, and quantified impact.
              </p>
            </div>
          </div>

          <div className="space-y-4">
            {aiSuggestions.map((suggestion, idx) => (
              <div
                key={idx}
                className="p-5 rounded-2xl bg-c-900/90 border border-c-700/70 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 hover:border-c-300/40 transition-colors"
              >
                <div className="flex items-start gap-3">
                  <span className="w-6 h-6 rounded-full bg-c-800 border border-c-700 text-c-300 text-xs font-heading font-bold flex items-center justify-center shrink-0 mt-0.5">
                    {idx + 1}
                  </span>
                  <p className="text-sm font-sans text-c-100 leading-relaxed">
                    {suggestion}
                  </p>
                </div>

                <button
                  type="button"
                  onClick={() => handleCopy(suggestion, idx)}
                  className="px-3.5 py-1.5 rounded-full bg-c-800 hover:bg-c-700 border border-c-600 text-xs font-heading font-semibold text-c-100 shrink-0 flex items-center gap-1.5 transition-colors cursor-pointer"
                >
                  {copiedIndex === idx ? (
                    <>
                      <Check size={13} className="text-c-success" />
                      <span className="text-c-success">Copied</span>
                    </>
                  ) : (
                    <>
                      <Copy size={13} />
                      <span>Copy Fix</span>
                    </>
                  )}
                </button>
              </div>
            ))}
          </div>
        </Card>
      )}
    </div>
  );
}
